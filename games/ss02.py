_COAT_CACHE = {}


def coat(name):
    """The head and body sprites recoloured for one of the FURS (built once, then reused)."""
    if name not in _COAT_CACHE:
        fur = FURS[name]
        table = np.arange(16, dtype=np.int16)
        table[ORG], table[MAR], table[RED], table[WHT], table[PNK] = fur["main"], fur["line"], fur["apron"], fur["muzzle"], fur["ear"]
        _COAT_CACHE[name] = tuple(np.where(part >= 0, table[np.clip(part, 0, 15)], -1) for part in (CAT_HEAD, CAT_BODY))
    return _COAT_CACHE[name]


