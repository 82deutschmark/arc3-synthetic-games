def draw_card(frame, lay, cx, order, width):
    """The order card standing beside a skewer: one slot per fruit, drawn at the same height as that fruit's place on
    the skewer. A picture is that fruit, a coloured square is any fruit of that colour, a black outline is any fruit of
    that shape."""
    x0, py = cx + 5, lay["py"]
    top = py - 8 - PITCH * (len(order) - 1) - 2
    rect(frame, x0, top, x0 + width - 1, py - 4, WHT)
    look = STYLES[lay["scene"]]
    frame_box(frame, x0, top, x0 + width - 1, py - 4, look["border"])
    rect(frame, x0 + 2, top - 2, x0 + 3, top, look["peg"])           # the clothes-peg that holds the card up
    for height, (mode, value) in enumerate(order):
        ix, iy = x0 + 1, py - 7 - PITCH * height
        if mode == "k":
            put(frame, ix, iy, FRUIT_MINI[value])
        elif mode == "c":
            rect(frame, ix, iy, ix + 4, iy + 4, CHIP[value])
            frame_box(frame, ix, iy, ix + 4, iy + 4, BLK)
        else:
            put(frame, ix, iy, FRUIT_MINI[value], only=BLK)


def draw_plate(frame, lay, cx, state_colour, glow):
    """The base plate under a skewer, outlined in black so it reads on any background: the setting's colour; light blue
    while selected; bright green when its stack is exactly right (the game's only sign of progress)."""
    py = lay["py"]
    done = state_colour == "done"
    fill = GRN if done else LBL if glow else STYLES[lay["scene"]]["plate"]
    light = GRN if done else WHT if glow else YEL
    rect(frame, cx - 5, py, cx + 4, py, BLK)
    rect(frame, cx - 6, py + 1, cx + 5, py + 2, BLK)
    rect(frame, cx - 5, py + 3, cx + 4, py + 3, BLK)
    rect(frame, cx - 5, py + 1, cx + 4, py + 1, light)
    rect(frame, cx - 5, py + 2, cx + 4, py + 2, fill)
    if done:
        dot(frame, cx - 3, py + 1, WHT)
        dot(frame, cx + 2, py + 2, WHT)


def draw_skewer(frame, lay, cx, capacity):
    """The wooden stick: long enough to show how many fruit it will take, with a bright tip."""
    top = lay["py"] - 8 - PITCH * (capacity - 1) - 3
    colours = STYLES[lay["scene"]]["pole"]
    for row in range(top, lay["py"]):
        dot(frame, cx, row, colours[(row // 2) % len(colours)])
    rect(frame, cx, top, cx, top + 1, YEL)
    dot(frame, cx, top, WHT)


POINTER = art(["kkkkk", ".kwk.", "..k.."])


def draw_pointer(frame, lay, cx, capacity, clock, dip=0):
    """The little arrow over the chosen skewer; it bobs, and dips `dip` rows when a skewer has just been picked."""
    top = lay["py"] - 8 - PITCH * (capacity - 1) - 3
    put(frame, cx - 2, top - 4 - (clock // 2) % 2 + dip, POINTER)


def draw_bracket(frame, x, y, colour):
    """Four white corners round an 8x8 slot: the fruit that will be threaded next."""
    for cx_, cy_, sx, sy in ((x, y, 1, 1), (x + 7, y, -1, 1), (x, y + 7, 1, -1), (x + 7, y + 7, -1, -1)):
        dot(frame, cx_, cy_, colour)
        dot(frame, cx_ + sx, cy_, colour)
        dot(frame, cx_, cy_ + sy, colour)


def draw_tray(frame, lay, tray, queue, selected, hide_tail, clock, style):
    x0, y0, x1, y1 = tray_rect(lay, tray)
    rim, inner = style
    rect(frame, x0, y0, x1, y1, rim)
    rect(frame, x0 + 1, y0 + 1, x1 - 1, y1 - 1, inner)
    for index, kind in enumerate(queue):
        if hide_tail and index == len(queue) - 1:
            continue
        x, y = tray_slot_xy(lay, tray, index)
        lift = 1 if index == 0 and selected and clock % 4 < 2 else 0
        put(frame, x, y - lift, FRUIT_ART[kind])
    if queue and selected:
        x, y = tray_slot_xy(lay, tray, 0)
        draw_bracket(frame, x, y, WHT)


