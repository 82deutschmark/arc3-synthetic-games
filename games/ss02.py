def draw_card(frame, lay, cx, order, width):
    """The order card standing beside a skewer: one slot per fruit, drawn at the same height as that fruit's place on
    the skewer. A picture is that fruit, a coloured square is any fruit of that colour, a black outline is any fruit of
    that shape."""
    x0, py = cx + 5, lay["py"]
    top = py - 8 - PITCH * (len(order) - 1) - 2
    rect(frame, x0, top, x0 + width - 1, py - 4, WHT)
    look = STYLES[lay["scene"]]
    frame_box(frame, x0, top, x0 + width - 1, py - 4, look["border"])
    rect(frame, x0 + 2, top - 2, x0 + 3, top, look["peg"])           # the clothes-peg that holds the card up
    for height, (mode, value) in enumerate(order):
        ix, iy = x0 + 1, py - 7 - PITCH * height
        if mode == "k":
            put(frame, ix, iy, FRUIT_MINI[value])
        elif mode == "c":
            rect(frame, ix, iy, ix + 4, iy + 4, CHIP[value])
            frame_box(frame, ix, iy, ix + 4, iy + 4, BLK)
        else:
            put(frame, ix, iy, FRUIT_MINI[value], only=BLK)


def draw_plate(frame, lay, cx, state_colour, glow):
    """The base plate under a skewer, outlined in black so it reads on any background: the setting's colour; light blue
    while selected; bright green when its stack is exactly right (the game's only sign of progress)."""
    py = lay["py"]
    done = state_colour == "done"
    fill = GRN if done else LBL if glow else STYLES[lay["scene"]]["plate"]
    light = GRN if done else WHT if glow else YEL
    rect(frame, cx - 5, py, cx + 4, py, BLK)
