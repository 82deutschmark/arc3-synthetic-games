def house(frame, x, base, w, h, wall, roof, lit=YEL, door=MAR):
    """A little townhouse standing on row `base`: wall, three-row roof, windows and a door."""
    rect(frame, x, base - h + 1, x + w - 1, base, wall)
    for k in range(3):
        rect(frame, x - 1 + k, base - h - k, x + w - k, base - h - k, roof)
    for wx in (x + 1, x + w - 3):
        rect(frame, wx, base - h + 3, wx + 1, base - h + 4, lit)
        dot(frame, wx, base - h + 5, RED)                         # a flower box under each window
