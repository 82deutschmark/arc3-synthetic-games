class MarketDisplay(RenderableUserDisplay):
    """Paints the whole 64x64 picture from the game's state each frame."""

    def __init__(self, game):
        self.game = game

    def rack_position(self, fx, skewer):
        """Rack places are floats while the rack turns: place 0 is the leftmost, 3 the rightmost."""
        g = self.game
        n = len(g.spec["orders"])
        if "rot" in fx:
            start, shift, frac = fx["rot"]
            return (slot_of(g.spec, start, skewer) - shift * frac) % n
        return slot_of(g.spec, fx.get("sel", g.state[0]), skewer)

    def render_interface(self, frame):
        g = self.game
        spec, lay, fx = g.spec, g.lay, g.fx
        sel, src, stacks, feeds = g.state
        SCENES[lay["scene"]](frame, g.clock, lay)
        # feeds: a conveyor or trays
        if spec.get("belt"):
            draw_belt(frame, lay, lay["scene"], feeds[0], fx.get("belt", 0), g.anim_ring if "belt" in fx else None, g.clock)
        else:
            style = TRAY_STYLE[lay["scene"]]
            for tray, queue in enumerate(feeds):
                chosen = tray == src
                rim = style[0] if len(feeds) == 1 or not chosen else YEL
                draw_tray(frame, lay, tray, queue, chosen, fx.get("hide_tail") == tray, g.clock, (rim, style[1]))
        blender_top = None
        if "blender" in lay:
            draw_blender(frame, lay, g.juice, g.clock)
            blender_top = blender_mouth(lay)
        # skewers (rack skewers are drawn in place order so a wrapping one never hides the others)
        count = len(spec["orders"])
        pitch = lay["cx"][1] - lay["cx"][0]
        spinning = "rot" in fx
        for skewer in range(count):
            order = spec["orders"][skewer]
            if spec.get("rack"):
                cx = lay["cx"][0] + round(pitch * self.rack_position(fx, skewer))
            else:
                cx = lay["cx"][skewer]
            done = plate_green(spec, g.state, skewer)
            chosen = skewer == sel and not spinning
            draw_card(frame, lay, cx, order, lay["cardw"])
            draw_skewer(frame, lay, cx, len(order))
            draw_plate(frame, lay, cx, "done" if done else "idle", chosen)
            for height, kind in enumerate(stacks[skewer]):
                if fx.get("hide") == (skewer, height):
                    continue
                x, y = stack_xy(lay, cx, height)
                if done and (g.clock // 2 + height) % 4 == 0:        # a finished stack does a little wave
                    y -= 1
                put(frame, x, y, FRUIT_ART[kind])
            if chosen:
                draw_pointer(frame, lay, cx, len(order), g.clock)
            if done and not spinning:
                for corner, (dx, dy) in enumerate(((-6, 0), (5, 0), (-6, 2), (5, 2))):
                    if (g.clock + corner) % 5 == 0:
                        sparkle(frame, cx + dx, lay["py"] + dy - 2, 0)
        if "fly" in fx:
            kind, x, y = fx["fly"]
            put(frame, x, y, FRUIT_ART[kind])
        for x, y, phase in fx.get("spark", ()):
            sparkle(frame, x, y, phase)
        if "splash" in fx and blender_top:
            splash(frame, blender_top[0], blender_top[1], fx["splash"][0], fx["splash"][1])
        if "confetti" in fx:
            confetti(frame, fx["confetti"], g.clock)
        if g.lost:
            frame[4:] = DIMMER[frame[4:]]
        # the vendor cat watches the selected skewer
        cat_x, cat_y = lay["cat"]
        target = skewer_column(spec, lay, sel, sel) + 3
        look = -1 if target < cat_x - 4 else 1 if target > cat_x + 12 else 0
        if spec.get("belt"):
            look = 0
        blink = g.clock % 23 in (0, 1)
        bounce = -1 if g.mood == "happy" and g.clock % 2 else 0
        draw_cat(frame, cat_x, cat_y + bounce, lay["fur"], g.mood, look, blink, lay.get("hat"), lay.get("bust", False),
                 (g.clock // 4) % 2, g.point[0] if g.point[1] > 0 else 0)
        draw_fuse(frame, g.counter, g.budget, g.clock)
        return frame


# ───────────────────────────── the game ─────────────────────────────
ANIM = 3          # frames in each little animation (a flight, a rack turn, a belt step)


def lerp_flight(a, b, step):
    """Position part-way along an arc from a to b (step 1..ANIM)."""
    t = step / (ANIM + 1)
    return round(a[0] + (b[0] - a[0]) * t), round(a[1] + (b[1] - a[1]) * t - 5 * np.sin(np.pi * t))


class Ss02(ARCBaseGame):
    def __init__(self):
        self.level_number = 0
        self.spec, self.lay = LEVELS[0], LAYOUT[0]
        self.state = start_state(self.spec)
        self.history, self.fx, self.pending, self.after = [], {}, None, None
        self.counter, self.budget = 1, 1
        self.clock, self.anim_ring = 0, None
        self.mood, self.mood_timer, self.lost, self.juice, self.point = "idle", 0, False, [], (0, 0)
        self.display = MarketDisplay(self)
        levels = [Level(sprites=[], grid_size=(64, 64), data={}, name=f"ss02-{i + 1}") for i in range(len(LEVELS))]
        super().__init__(game_id="ss02", levels=levels,
                         camera=Camera(x=0, y=0, width=64, height=64, background=BLK, letter_box=BLK,
                                       interfaces=[self.display]),
                         debug=False, win_score=len(levels), available_actions=[5, 6, 7])

    # Every per-level thing is (re)set here, so RESET refills the fuse and puts the fruit back.
    def on_set_level(self, level):
        self.level_number = self.level_index
        self.spec, self.lay = LEVELS[self.level_number], LAYOUT[self.level_number]
        self.state = start_state(self.spec)
        self.history, self.fx, self.pending, self.after = [], {}, None, None
        self.budget = self.counter = self.spec["budget"]
        self.clock, self.anim_ring = 0, None
        self.mood, self.mood_timer, self.lost, self.juice, self.point = "idle", 0, False, [], (0, 0)

    # ── one action = one call to run_action, then a few frames of animation ──
    def step(self):
        self.clock += 1
        if self.point[1] > 0:
            self.point = (self.point[0], self.point[1] - 1)
        if self.mood_timer > 0:
            self.mood_timer -= 1
            if self.mood_timer == 0 and not self.lost:
                self.mood = "worry" if self.counter * 4 <= self.budget else "idle"
        if self.action.id.value == 0:          # RESET: the engine has already rebuilt the level
            self.complete_action()
            return
        if self.pending is None:
            self.pending = self.run_action()
        self.fx = self.pending.pop(0) if self.pending else {}
        if self.pending:
            return
        self.pending, after, self.after = None, self.after, None
        if after == "next":
            self.next_level()
        elif after == "lose":
            self.lose()
        self.complete_action()

    def feel(self, mood, frames=7):
        self.mood, self.mood_timer = mood, frames

    def run_action(self):
        spec, lay = self.spec, self.lay
        button = self.action.id.value
        data = self.action.data or {}
        sel_before = self.state[0]
        if button == 5:
            action = ("thread",)
        elif button == 6:
            action = click_to_action(spec, lay, sel_before, data.get("x", -1), data.get("y", -1))
        elif button == 7:
            action = ("undo",)
        else:
            action = ("wait",)
        self.counter -= 1
        before = self.state
        frames = []
        if action[0] in ("pick", "feed"):          # the vendor points at what the player just chose
            if action[0] == "feed":
                aim = sum(tray_rect(lay, action[1])[0::2]) // 2
            else:
                aim = skewer_column(spec, lay, sel_before, action[1])
            self.point = (-1 if aim < lay["cat"][0] + 5 else 1, 6)
        if action[0] == "undo":
            # undo puts the board back as it was before the last action that changed it; it never refunds the fuse
            if self.history:
                self.state = self.history.pop()
                frames = [{"spark": [(lay["cx"][min(self.state[0], len(lay["cx"]) - 1)], lay["py"] - 4, 0)]}]
        else:
            new, extra, event = apply_action(spec, before, action)
            if new != before:
                self.history.append(before)
            self.state = new
            self.counter -= extra
            frames = self.frames_for(before, new, event, action)
        done = solved(spec, self.state)
        if done:
            frames += [{"confetti": phase} for phase in range(5)]
            self.feel("happy", 12)
            self.after = "next"
        elif self.counter <= 0:
            self.counter = 0
            self.lost = True
            self.feel("sad", 99)
            frames += [{}, {}]
            self.after = "lose"
        if not frames:
            frames = [{}]
        return frames

    def frames_for(self, before, new, event, action):
        """The little animation for what just happened: a flight to a skewer or to the blender, a rack turn, a belt step."""
        spec, lay = self.spec, self.lay
        kind = event[0]
        frames = []
        belt = bool(spec.get("belt"))
        if belt:
            ring = before[3][0]
            self.anim_ring = (EMPTY,) + ring[1:] if kind in ("place", "blend") else ring
        if kind in ("place", "blend"):
            sel, src = before[0], before[1]
            fruit = before[3][src][0]
            start = belt_slot_xy(lay, 0) if belt else tray_slot_xy(lay, src, 0)
            if kind == "place":
                column = skewer_column(spec, lay, sel, sel)
                end = stack_xy(lay, column, event[2])
                for step in range(1, ANIM + 1):
                    x, y = lerp_flight(start, end, step)
                    frames.append({"fly": (fruit, x, y), "hide": (sel, event[2]), "sel": sel})
                stack = new[2][sel]
                if plate_green(spec, new, sel):
                    self.feel("happy", 8)
                    cx = column
                    frames += [{"spark": [(cx - 6, lay["py"], phase), (cx + 5, lay["py"], phase),
                                          (cx, lay["py"] - 9 - PITCH * (len(stack) - 1), phase)]} for phase in range(3)]
                if spec.get("rack"):
                    frames += [{"rot": (sel, 1, step / (ANIM + 1))} for step in range(1, ANIM + 1)]
            else:
                bx, by = blender_mouth(lay)
                for step in range(1, ANIM + 1):
                    x, y = lerp_flight(start, (bx - 4, by - 3), step)
                    frames.append({"fly": (fruit, x, y), "hide_tail": src})
                for phase in range(2):
                    frames.append({"splash": (FRUIT_JUICE[fruit], phase), "hide_tail": src})
                self.juice.append(FRUIT_JUICE[fruit])
                self.feel("worry", 8)
                if spec.get("rack"):
                    frames += [{"rot": (sel, 1, step / (ANIM + 1))} for step in range(1, ANIM + 1)]
        elif kind == "pick" and spec.get("rack") and action[1] != before[0]:
            n = len(spec["orders"])
            shift = (slot_of(spec, before[0], action[1]) - RACK_WINDOW) % n
            if shift > n // 2:
                shift -= n
            frames = [{"rot": (before[0], shift, step / (ANIM + 1))} for step in range(1, ANIM + 1)]
        elif kind == "refused":
            self.feel("worry", 4)
        if belt:
            if not frames:
                frames = [{} for _ in range(ANIM)]
            for index, frame in enumerate(frames[:ANIM]):
                frame["belt"] = (index + 1) / (ANIM + 1)
        return frames
