# ───────────────────────────── geometry shared by the rules' hit test and the art ─────────────────────────────
def stack_xy(lay, cx, height):
    """Top-left corner of the fruit at this height of a skewer centred on column cx."""
    return cx - 4, lay["py"] - 8 - PITCH * height


def tray_slot_xy(lay, tray, index):
    x, y, columns, _rows = lay["trays"][tray]
    return x + 8 * (index % columns), y + 8 * (index // columns)


def tray_rect(lay, tray):
    x, y, columns, rows = lay["trays"][tray]
    return x - 1, y - 1, x + 8 * columns, y + 8 * rows


def belt_slot_xy(lay, p):
    """Top-left corner of belt slot p: slots 0..5 ride the top run (leftward), 6..11 the bottom run (rightward)."""
    x0, y_top, y_bottom = lay["belt"]
    if p < 6:
        return x0 + 8 * p, y_top
    return x0 + 8 * (11 - p), y_bottom


def slot_of(spec, sel, skewer):
    """Which of the rack's four places a skewer sits in when `sel` is in the window."""
    return (skewer - sel + RACK_WINDOW) % len(spec["orders"])


def skewer_column(spec, lay, sel, skewer):
    if spec.get("rack"):
        return lay["cx"][slot_of(spec, sel, skewer)]
    return lay["cx"][skewer]


def click_to_action(spec, lay, sel, x, y):
    """What a click at (x, y) means: pick a skewer, choose a tray, or nothing (still costs the action)."""
    if not (isinstance(x, (int, float)) and isinstance(y, (int, float)) and isfinite(x) and isfinite(y)):
        return ("wait",)
    if len(spec["feeds"]) > 1 and "trays" in lay:
        for tray in range(len(lay["trays"])):
            x0, y0, x1, y1 = tray_rect(lay, tray)
            if x0 <= x <= x1 and y0 <= y <= y1:
                return ("feed", tray)
    if 4 <= y <= lay["py"] + 4:
        limit = lay["blender"][0] - 1 if "blender" in lay and lay["blender"][1] < lay["py"] else 64
        if x < limit:
            columns = lay["cx"][:len(spec["orders"])]
            nearest = min(range(len(columns)), key=lambda i: abs(x - columns[i] - 3))
            if spec.get("rack"):
                # whichever skewer is sitting in that place of the rack
                return ("pick", next(i for i in range(len(columns)) if slot_of(spec, sel, i) == nearest))
            return ("pick", nearest)
    return ("wait",)



