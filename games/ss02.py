def draw_bracket(frame, x, y, colour):
    """Four white corners round an 8x8 slot: the fruit that will be threaded next."""
    for cx_, cy_, sx, sy in ((x, y, 1, 1), (x + 7, y, -1, 1), (x, y + 7, 1, -1), (x + 7, y + 7, -1, -1)):
        dot(frame, cx_, cy_, colour)
        dot(frame, cx_ + sx, cy_, colour)
        dot(frame, cx_, cy_ + sy, colour)


def draw_tray(frame, lay, tray, queue, selected, hide_tail, clock, style):
    x0, y0, x1, y1 = tray_rect(lay, tray)
    rim, inner = style
    rect(frame, x0, y0, x1, y1, rim)
    rect(frame, x0 + 1, y0 + 1, x1 - 1, y1 - 1, inner)
    for k in range(x0 + 4, x1, 8):                                  # rivets along the rim
        dot(frame, k, y0, YEL)
        dot(frame, k, y1, YEL)
    for index, kind in enumerate(queue):
        if hide_tail and index == len(queue) - 1:
            continue
        x, y = tray_slot_xy(lay, tray, index)
        lift = 1 if index == 0 and selected and clock % 4 < 2 else 0
        put(frame, x, y - lift, FRUIT_ART[kind])
    if queue and selected:
        x, y = tray_slot_xy(lay, tray, 0)
        draw_bracket(frame, x, y, WHT)


