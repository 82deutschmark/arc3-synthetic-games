def draw_cat(frame, x, y, fur="tabby", mood="idle", look=0, blink=False, hat=None, bust=False, tail=0, point=0):
    """The vendor cat in the given coat, with blinking eyes that follow `look` (-1 left, 0 ahead, 1 right) and a mood."""
    head, body = coat(fur)
    eye, tail_colour = FURS[fur]["eye"], FURS[fur]["main"]
    if not bust:
        put(frame, x, y + 8, body)
        # tail: swishes between two curls
        for tx, ty in (((10, 12), (11, 12), (11, 11), (11, 10)) if tail else ((10, 12), (11, 12), (12, 11), (12, 10))):
            dot(frame, x + tx, y + ty, tail_colour)
    else:
        put(frame, x, y + 8, body[:3])
    put(frame, x, y, head)
    if point:                                               # pointing at what was just picked
        start = x - 1 if point < 0 else x + 10
        rect(frame, min(start, start + 3 * point), y + 9, max(start, start + 3 * point), y + 9, tail_colour)
        dot(frame, start + 3 * point, y + 9, WHT)
    if mood == "happy" and not bust:                        # cheering: both paws up
        for arm_x in (x - 1, x + 10):
            rect(frame, arm_x, y + 6, arm_x, y + 10, tail_colour)
            dot(frame, arm_x, y + 5, WHT)
    if hat:
        put(frame, x + 2, y - 2, CAT_HATS[hat])
    for ex in (1, 7):                       # eyes: two columns wide, rows 3-4 of the head
        if mood == "happy":
            dot(frame, ex + x, y + 4, eye)
            dot(frame, ex + x + 1, y + 3, eye)
        elif blink:
            rect(frame, ex + x, y + 4, ex + x + 1, y + 4, eye)
        else:
            rect(frame, ex + x, y + 3, ex + x + 1, y + 4, eye)
            dot(frame, ex + x + (1 if look > 0 else 0), y + 3, WHT)         # the glint shows where it is looking
            if mood in ("worry", "sad"):
                rect(frame, ex + x - 1, y + 2, ex + x + 2, y + 2, MAR)
            if mood == "sad":
                dot(frame, ex + x + (0 if ex == 1 else 1), y + 5, LBL)
    if mood == "worry":
        dot(frame, x + 10, y + 1 + tail, LBL)          # a bead of sweat
    rect(frame, x + 4, y + 5, x + 5, y + 5, MAG)        # nose
    if mood == "happy":
        dot(frame, x + 3, y + 6, BLK)
        dot(frame, x + 6, y + 6, BLK)
        rect(frame, x + 4, y + 6, x + 5, y + 6, RED)
    elif mood in ("worry", "sad"):
        rect(frame, x + 4, y + 6, x + 5, y + 6, BLK)
        dot(frame, x + 3, y + 7, BLK)
        dot(frame, x + 6, y + 7, BLK)
    else:
        rect(frame, x + 4, y + 6, x + 5, y + 6, BLK)
    for wy in (5, 6):                                     # whiskers
        dot(frame, x - 1, y + wy, WHT)
        dot(frame, x + 10, y + wy, WHT)


# ───────────────────────────── the fuse (the move counter) ─────────────────────────────
def draw_fuse(frame, counter, budget, clock):
    """A burning fuse along the top: its length is the counter. It shortens with every action and turns red when
    a quarter is left. No digits anywhere."""
    rect(frame, 0, 0, 63, 3, BLK)
    width = 60
    lit = 0 if counter <= 0 else max(1, -(-width * counter // budget))
    low = counter * 4 <= budget
    top, bottom = (RED, ORG) if low and clock % 2 else (YEL, ORG)
    rect(frame, 2, 1, 2 + width - 1, 2, MAR)
    if lit:
        rect(frame, 2, 1, 2 + lit - 1, 1, top)
        rect(frame, 2, 2, 2 + lit - 1, 2, bottom)
        spark = 2 + lit
        dot(frame, spark, 1, WHT)
        dot(frame, spark, 0 if clock % 2 else 2, YEL)
        dot(frame, spark + 1, 1, ORG if clock % 2 else YEL)
    for mark in range(5, budget, 5):                       # a ruler of five-action ticks along the bottom of the fuse
        dot(frame, 2 + (width * mark) // budget, 3, MAR)


