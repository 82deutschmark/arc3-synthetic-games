# ───────────────────────────── action reactions (drawn only from the fx of the frame being shown) ─────────────────────────────
def dust(frame, cx, y, step):
    """Two little puffs either side of a plate when a fruit lands; they drift outward over the beat."""
    for side in (-1, 1):
        dot(frame, cx + side * (6 + step), y, WHT)
        dot(frame, cx + side * (7 + step), y - 1, YEL)


def ripple(frame, x, y, step):
    """A ring that grows round a missed click: dashed yellow and black so it reads on any backdrop."""
    for k, (dx, dy) in enumerate(RAYS):
        dot(frame, x + dx * step * 2, y + dy * step * 2, YEL if k % 2 else BLK)


def curtain(frame, step):
    """The level-change wipe: black curtains close in from both sides, each with a bright edge."""
    reach = step * 11
    rect(frame, 0, 4, reach - 1, 63, BLK)
    rect(frame, 64 - reach, 4, 63, 63, BLK)
    if reach < 32:
        rect(frame, reach, 4, reach, 63, YEL)
        rect(frame, 63 - reach, 4, 63 - reach, 63, YEL)


def puff(frame, x, y, phase):
    """A curl of smoke rising from a burnt-out fuse."""
    for k in range(3):
        rise = phase * 3 + k * 3
        px, py = x + (1 if (k + phase) % 2 else 0), y + rise
        rect(frame, px, py, px + 1, py + 1, WHT)


