LEGEND = dict(k=BLK, w=WHT, r=RED, d=MAR, o=ORG, y=YEL, g=GRN, b=BLU, l=LBL, p=PUR, n=PNK, m=MAG)


def art(rows):
    out = np.full((len(rows), len(rows[0])), -1, dtype=np.int16)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch != ".":
                out[y, x] = LEGEND[ch]
    return out


def put(frame, x, y, sprite, flip=False, only=None):
    """Blit a sprite at (x, y), clipped. `only` paints every opaque pixel in that single colour (silhouettes)."""
    if flip:
        sprite = sprite[:, ::-1]
    h, w = sprite.shape
    x0, y0 = max(0, -x), max(0, -y)
    x1, y1 = min(w, 64 - x), min(h, 64 - y)
    if x1 <= x0 or y1 <= y0:
        return
    part = sprite[y0:y1, x0:x1]
    view = frame[y + y0:y + y1, x + x0:x + x1]
    mask = part >= 0
    view[mask] = only if only is not None else part[mask]


def rect(frame, x0, y0, x1, y1, colour):
    """Filled rectangle, corners inclusive, clipped."""
    x0, y0, x1, y1 = max(0, x0), max(0, y0), min(63, x1), min(63, y1)
    if x1 >= x0 and y1 >= y0:
        frame[y0:y1 + 1, x0:x1 + 1] = colour


def dot(frame, x, y, colour):
    if 0 <= x < 64 and 0 <= y < 64:
        frame[y, x] = colour


def frame_box(frame, x0, y0, x1, y1, colour):
    rect(frame, x0, y0, x1, y0, colour)
    rect(frame, x0, y1, x1, y1, colour)
    rect(frame, x0, y0, x0, y1, colour)
    rect(frame, x1, y0, x1, y1, colour)


def disc(frame, cx, cy, radius, colour):
    for yy in range(-radius, radius + 1):
        for xx in range(-radius, radius + 1):
            if xx * xx + yy * yy <= radius * radius + radius // 2:
                dot(frame, cx + xx, cy + yy, colour)


