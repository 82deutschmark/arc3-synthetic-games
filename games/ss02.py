# colour class a fruit belongs to (for colour-order slots) and the shape class (named by its first member)
COLOUR_OF = {APPLE: 0, ORANGE: 1, GRAPES: 2, BANANA: 3, BERRY: 0, PINE: 3, MELON: 4, CHERRY: 0, PLUM: 2}
SHAPE_OF = {APPLE: APPLE, ORANGE: APPLE, PLUM: APPLE, GRAPES: GRAPES, BANANA: BANANA, BERRY: BERRY,
            PINE: PINE, MELON: MELON, CHERRY: CHERRY}
