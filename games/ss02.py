EMPTY = -1
BLEND_EXTRA = 2        # a fruit sent to the blender costs this much counter on top of the action itself


def exact(kind):
    """A slot that wants exactly this fruit (drawn as the fruit)."""
    return ("k", kind)


def by_colour(colour):
    """A slot that takes any fruit of this colour (drawn as a colour chip)."""
    return ("c", colour)


def by_shape(kind):
    """A slot that takes any fruit with this fruit's outline (drawn as a black silhouette)."""
    return ("s", SHAPE_OF[kind])


def accepts(slot, kind):
    mode, value = slot
    if mode == "k":
        return kind == value
    if mode == "c":
        return COLOUR_OF[kind] == value
    return SHAPE_OF[kind] == value


def stack_right(order, stack):
    """True when the stack is a correct start of the order (every fruit so far fits its slot)."""
    return len(stack) <= len(order) and all(accepts(order[i], kind) for i, kind in enumerate(stack))


# ───────────────────────────── the rules, as pure functions of a state tuple ─────────────────────────────
# state = (selected skewer, selected tray, stacks, feeds)
#   stacks: one tuple of fruit per skewer, bottom first.
#   feeds:  one tuple per tray, the next fruit first; a conveyor is one ring tuple whose index 0 is the pick-up spot
#           and whose EMPTY entries are bare belt.
# actions: ("thread",)  put the next fruit on the selected skewer
#          ("pick", i)  select skewer i            ("feed", j)  select tray j
#          ("wait",)    a click on nothing (the conveyor still runs)

def start_state(spec):
    return (0, 0, tuple(() for _ in spec["orders"]), tuple(tuple(feed) for feed in spec["feeds"]))


def solved(spec, state):
    _, _, stacks, _ = state
    return all(len(stack) == len(order) and stack_right(order, stack) for order, stack in zip(spec["orders"], stacks))


def plate_green(spec, state, stick):
    """The only progress signal: this skewer's stack is complete and right."""
    stack = state[2][stick]
    return len(stack) == len(spec["orders"][stick]) and stack_right(spec["orders"][stick], stack)


def apply_action(spec, state, action):
    """Return (new state, extra counter cost, event). The event only tells the art what to animate."""
    sel, src, stacks, feeds = state
    kind = action[0]
    extra, event = 0, (kind,)
    if kind == "thread":
        feed = feeds[src]
        front = feed[0] if feed else EMPTY
        stack, order = stacks[sel], spec["orders"][sel]
        if front == EMPTY or len(stack) >= len(order):
            event = ("refused", sel, src)
        else:
            wrong = spec.get("blender") and not accepts(order[len(stack)], front)
            feeds = list(feeds)
            if wrong:
                # the fruit is blended; the stall tosses a fresh one of the same kind onto the back of the same tray
                feeds[src] = feed[1:] + (front,)
                extra, event = BLEND_EXTRA, ("blend", sel, src, front)
            else:
                stacks = list(stacks)
                stacks[sel] = stack + (front,)
                stacks = tuple(stacks)
                feeds[src] = (EMPTY,) + feed[1:] if spec.get("belt") else feed[1:]
                event = ("place", sel, len(stack), src, front)
            feeds = tuple(feeds)
            if spec.get("rack"):
                sel = (sel + 1) % len(stacks)
    elif kind == "pick":
        sel = action[1]
    elif kind == "feed":
        src = action[1]
    if spec.get("belt"):
        ring = feeds[0]
        feeds = (ring[1:] + ring[:1],)
    return (sel, src, stacks, feeds), extra, event


def legal_actions(spec, state):
    acts = [("thread",), ("wait",)]
    acts += [("pick", i) for i in range(len(spec["orders"]))]
    acts += [("feed", j) for j in range(len(spec["feeds"])) if len(spec["feeds"]) > 1]
    return acts


def shortest_line(spec, limit=3_000_000):
    """Cheapest winning line as (total counter cost, list of actions), found by Dijkstra over apply_action. Where there
    is no blender a wrong fruit can never come off again, so those dead states are skipped: no shortest line uses them."""
    begin = start_state(spec)
    best, came = {begin: 0}, {begin: None}
    heap = [(0, 0, begin)]
    tie = 0
    while heap and len(best) < limit:
        cost, _, state = heapq.heappop(heap)
        if cost > best[state]:
            continue
        if solved(spec, state):
            line = []
            while came[state] is not None:
                state, action = came[state]
                line.append(action)
            return cost, line[::-1]
        for action in legal_actions(spec, state):
            nxt, extra, _event = apply_action(spec, state, action)
            if nxt == state:
                continue
            if not spec.get("blender") and not all(stack_right(o, s) for o, s in zip(spec["orders"], nxt[2])):
                continue
            new_cost = cost + 1 + extra
            if new_cost < best.get(nxt, 1 << 30):
                best[nxt] = new_cost
                came[nxt] = (state, action)
                tie += 1
                heapq.heappush(heap, (new_cost, tie, nxt))
    return None, []


def shortest_cost(spec, limit=3_000_000):
    return shortest_line(spec, limit)[0]


