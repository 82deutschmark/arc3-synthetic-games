BELT_STYLES = {
    "cannery": dict(surface=BLU, stripe=LBL, rail=BLK, accent=YEL),
    "pier": dict(surface=MAR, stripe=ORG, rail=BLK, accent=YEL),
}


def draw_belt(frame, lay, style, ring, moving, anim_ring, beat):
    """A looping conveyor: the top run carries fruit left to the pick-up spot (a bracket and arrow), the bottom run
    carries them back. `moving` is how far (0..1) the belt has gone through the current tick."""
    x0, y_top, y_bottom = lay["belt"]
    look = BELT_STYLES[style]
    shift = round(8 * moving) if anim_ring else 0
    for run_y, direction in ((y_top, -1), (y_bottom, 1)):
        rect(frame, x0 - 3, run_y - 1, x0 + 50, run_y + 7, look["surface"])
        for k in range(0, 56, 8):                            # cross-bars that slide with the belt
            x = x0 - 3 + (k + direction * shift) % 56
            rect(frame, x, run_y - 1, x, run_y + 7, look["stripe"])
        rect(frame, x0 - 3, run_y + 8, x0 + 50, run_y + 8, look["rail"])
        for k in range(x0 - 3, x0 + 51, 6):                   # warning blocks along the lower rail
            rect(frame, k, run_y + 8, k + 2, run_y + 8, look["accent"])
    rect(frame, x0 - 4, y_top - 1, x0 - 4, y_bottom + 8, look["rail"])
    rect(frame, x0 + 51, y_top - 1, x0 + 51, y_bottom + 8, look["rail"])
    for run_y in (y_top, y_bottom):                                  # end rollers with a turning spoke
        for roller_x in (x0 - 2, x0 + 49):
            rect(frame, roller_x, run_y + 1, roller_x + 2, run_y + 6, look["rail"])
            dot(frame, roller_x + 1, run_y + 2 + shift % 4, look["accent"])
    # the items
    if anim_ring and 0 < moving < 1:
        count = len(anim_ring)
        for p, kind in enumerate(anim_ring):
            if kind == EMPTY:
                continue
            ax, ay = belt_slot_xy(lay, p)
            bx, by = belt_slot_xy(lay, (p - 1) % count)
            put(frame, round(ax + (bx - ax) * moving), round(ay + (by - ay) * moving), FRUIT_ART[kind])
    else:
        for p, kind in enumerate(ring):
            if kind != EMPTY:
                x, y = belt_slot_xy(lay, p)
                put(frame, x, y, FRUIT_ART[kind])
    px, py_ = belt_slot_xy(lay, 0)                                    # the pick-up spot: a frame that pulses
    pulse = WHT if beat % 2 else YEL
    frame_box(frame, px - 1, py_ - 1, px + 8, py_ + 8, pulse)
    draw_bracket(frame, px, py_, pulse)


def blender_mouth(lay):
    """Where a blended fruit flies to: just above the blender's lid."""
    bx, by = lay["blender"]
    return bx + 4, by - 2


def draw_blender(frame, lay, juice, spin):
    """A smoothie blender: lid, glass jug that fills with the juice of every blended fruit, a motor with a dial."""
    bx, by = lay["blender"]
    jug = 14 if lay["scene"] == "smoothie" else 10
    rect(frame, bx + 1, by, bx + 8, by + 1, RED)                       # lid
    rect(frame, bx + 3, by - 1, bx + 6, by - 1, MAR)
    rect(frame, bx, by + 2, bx + 9, by + 1 + jug, WHT)                  # glass
    rect(frame, bx + 1, by + 2, bx + 8, by + jug, LBL)
    rect(frame, bx + 1, by + 2, bx + 1, by + 6, WHT)                    # the shine down one side
    bottom = by + jug
    for layer, colour in enumerate(juice[-(jug // 2 - 1):]):
        rect(frame, bx + 1, bottom - 2 * layer - 1, bx + 8, bottom - 2 * layer, colour)
    for k in range(1, 8, 2):                                            # blades: they swap places every beat
        dot(frame, bx + k + spin % 2, bottom - 1 + (k // 2) % 2, BLK)
    rect(frame, bx, by + 2 + jug, bx + 9, by + 8 + jug, RED)            # motor
    rect(frame, bx, by + 7 + jug, bx + 9, by + 8 + jug, MAR)
    rect(frame, bx + 2, by + 4 + jug, bx + 3, by + 5 + jug, YEL)
    rect(frame, bx + 6, by + 4 + jug, bx + 7, by + 5 + jug, BLK)
    rect(frame, bx, by + 9 + jug, bx + 9, by + 9 + jug, BLK)


def sparkle(frame, x, y, phase):
    """A twinkling four-point star; phase 0..2 grows and fades."""
    colour = (YEL, WHT, YEL)[phase % 3]
    dot(frame, x, y, WHT)
    if phase % 3 != 2:
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            dot(frame, x + dx, y + dy, colour)
    if phase % 3 == 1:
        for dx, dy in ((2, 0), (-2, 0), (0, 2), (0, -2)):
            dot(frame, x + dx, y + dy, YEL)


def confetti(frame, phase, clock):
    """Level-clear shower: coloured bits fall in a fixed scatter."""
    colours = (RED, YEL, LBL, PNK, GRN, ORG, WHT, MAG)
    for k in range(34):
        x = (k * 37 + 11) % 62 + 1
        y = (k * 53 + phase * 9 + (k % 3) * 5) % 56 + 4
        rect(frame, x, y, x + (k % 2), y + 1, colours[k % 8])


def splash(frame, x, y, colour, phase):
    """Juice flying out of the blender lid: droplets fan out and fall; the first beat is the bigger burst."""
    for k, (dx, dy) in enumerate(((-3, -2), (3, -3), (-1, -4), (2, -5), (-5, 0), (5, -1), (0, -6), (-4, -4))):
        grow = phase + 1
        px, py = x + dx * grow // 2, y + dy * grow // 2 + phase * 2
        rect(frame, px, py, px + 1, py + 1, colour)
        if k % 2 == 0:
            dot(frame, px, py, WHT)


